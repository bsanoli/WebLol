import { expect, test, type Page } from "@playwright/test"
import { boxOf, required } from "./support/box"
import { size, visionButton, choose, mapPoint, drag, waitForRealisticMap } from "./support/tactical-map"

test("Destrói e restaura torres nas visões de equipe sem ligar o alcance de ataque", async ({ page }) => {
  await page.setViewportSize(size)
  await page.goto("/camp.html")
  await page.getByRole("button", { name: "Mapa tático" }).click()
  await waitForRealisticMap(page)
  const blue = page.getByRole("button", { name: "Torre externa do topo — Azul", exact: true })
  const red = page.getByRole("button", { name: "Torre externa do topo — Vermelho", exact: true })
  const reach = page.getByRole("switch", { name: "Alcance das torres" })
  const sight = page.locator('#tactical-fog [data-sight-source="tower"]')
  const rings = page.locator("#map-tower-ranges circle")

  await expect(blue).toBeHidden()
  await expect(reach).not.toBeChecked()
  await visionButton(page, "azul").click()
  await expect(blue).toBeVisible()
  await expect(red).toBeVisible()
  await expect(sight).toHaveCount(11)
  await expect(rings).toHaveCount(0)

  await blue.click()
  await expect(blue).toHaveAttribute("aria-pressed", "true")
  await expect(blue).toHaveAccessibleDescription("Destruída. Restaurar torre")
  await expect(blue).toBeFocused()
  await expect(sight).toHaveCount(10)
  await blue.press("Space")
  await expect(sight).toHaveCount(11)
  await expect(blue).toHaveAttribute("aria-pressed", "false")

  await red.click({ button: "right" })
  await page.getByRole("menuitem", { name: "Marcar como destruída", exact: true }).click()
  await expect(sight).toHaveCount(11)
  await visionButton(page, "vermelha").click()
  await expect(red).toHaveAttribute("aria-pressed", "true")
  await expect(sight).toHaveCount(10)
  await page.getByRole("button", { name: "Desfazer", exact: true }).click()
  await expect(red).toHaveAttribute("aria-pressed", "false")
  await expect(sight).toHaveCount(11)

  const combined = visionButton(page, "azul e vermelha")
  await combined.press("Space")
  await expect(combined).toHaveAttribute("aria-pressed", "true")
  await expect(visionButton(page, "vermelha")).toHaveAttribute("aria-pressed", "false")
  await expect(page.getByText("Prévia tática aproximada da visão das duas equipes.")).toBeVisible()
  await expect(page.locator("#tactical-fog [data-champion-sight]")).toHaveCount(10)
  await expect(sight).toHaveCount(22)
  await expect(rings).toHaveCount(0)
  await red.click()
  await expect(sight).toHaveCount(21)
  await red.click()
  await expect(sight).toHaveCount(22)
  await combined.click()
  await expect(visionButton(page, "geral")).toHaveAttribute("aria-pressed", "true")
  await expect(sight).toHaveCount(0)
  await combined.click()
  await page.getByRole("button", { name: "Resetar mapa" }).click()
  await expect(visionButton(page, "geral")).toHaveAttribute("aria-pressed", "true")
  await expect(red).toBeHidden()
  await expect(sight).toHaveCount(0)
  await reach.click()
  await expect(red).toBeVisible()
  await expect(rings).toHaveCount(22)
})

test("Projeta as waves nas curvas do mapa realista e mantém o progresso salvo", async ({ page }) => {
  await page.setViewportSize(size)
  await page.emulateMedia({ reducedMotion: "reduce" })
  await page.goto("/camp.html")
  await page.getByRole("button", { name: "Mapa tático" }).click()
  await waitForRealisticMap(page)
  await expect(page.locator("#mapimg")).toHaveAttribute("data-map-visible", "")
  const top = page.getByRole("button", { name: "Wave — Topo — Azul" })
  const bot = page.getByRole("button", { name: "Wave — Inferior — Azul" })
  const mid = page.getByRole("button", { name: "Wave — Meio — Azul" })
  const wavePoint = (wave: ReturnType<Page["locator"]>) =>
    wave.evaluate(node =>
      [parseFloat(node.style.left), parseFloat(node.style.top)].map(axis => Math.round(axis * 10) / 10),
    )
  const expectPoint = async (wave: ReturnType<Page["locator"]>, x: number, y: number) => {
    const [actualX, actualY] = await wavePoint(wave)
    expect(Math.hypot(actualX - x, actualY - y)).toBeLessThan(0.2)
  }

  const placeWave = page.getByRole("radio", { name: "Colocar wave azul", exact: true })
  await placeWave.click()
  const topCorner = await mapPoint(page, 0.15, 0.14)
  await page.mouse.move(topCorner.x, topCorner.y)
  await expectPoint(page.locator("#map-wave-preview"), 15, 14)
  await page.mouse.click(topCorner.x, topCorner.y)
  await expect(page.getByRole("radio", { name: "Mover", exact: true })).toBeChecked()
  await placeWave.click()
  const botCorner = await mapPoint(page, 0.855, 0.835)
  await page.mouse.click(botCorner.x, botCorner.y)
  await placeWave.click()
  const midPoint = await mapPoint(page, 0.49, 0.5)
  await page.mouse.click(midPoint.x, midPoint.y)
  await expectPoint(top, 15, 14)
  await expectPoint(bot, 85.5, 83.5)
  const middle = await wavePoint(mid)
  await page.getByRole("tab", { name: "Camadas" }).click()
  const realistic = page.getByRole("switch", { name: "Usar mapa realista" })
  await realistic.click()
  await expectPoint(top, 12, 12)
  await expectPoint(bot, 90, 87)
  expect(await wavePoint(mid)).toEqual(middle)
  await realistic.click()

  await page.getByRole("radio", { name: "Mover", exact: true }).click()
  await page.getByRole("tab", { name: "Sequência" }).click()
  await page.getByRole("button", { name: "Novo passo" }).click()
  for (const [wave, x, y] of [
    [top, 0.49, 0.085],
    [bot, 0.47, 0.91],
  ] as const) {
    const marker = await boxOf(wave)
    await drag(page, { x: marker.x + marker.width / 2, y: marker.y + marker.height / 2 }, await mapPoint(page, x, y))
    await expectPoint(wave, x * 100, y * 100)
  }
  const straight = [await wavePoint(top), await wavePoint(bot)]
  await page.getByRole("button", { name: "Novo passo" }).click()
  await page.getByRole("tab", { name: "Camadas" }).click()
  await realistic.click()
  expect([await wavePoint(top), await wavePoint(bot)]).toEqual(straight)
  await realistic.click()
  await page.getByRole("tab", { name: "Sequência" }).click()
  await page.getByRole("button", { name: "Selecionar passo 1" }).click()
  await expectPoint(top, 15, 14)
  await expectPoint(bot, 85.5, 83.5)
  await page.getByRole("button", { name: "Reproduzir" }).click()
  await expect(page.getByRole("button", { name: "Reproduzir" })).toBeVisible()
  expect([await wavePoint(top), await wavePoint(bot)]).toEqual(straight)
})

test("Move wards e waves, alterna a visão aliada e restaura o estado das torres por passo", async ({ page }) => {
  await page.setViewportSize(size)
  await page.emulateMedia({ reducedMotion: "reduce" })
  await page.goto("/camp.html")
  await page.getByRole("button", { name: "Mapa tático" }).click()
  await waitForRealisticMap(page)
  await page.getByRole("tab", { name: "Camadas" }).click()
  await page.getByRole("switch", { name: "Mostrar Lumes Feéricos" }).click()
  const light = page.getByRole("img", { name: "Arbusto ilhado do rio superior" })

  await page.getByRole("radio", { name: "Colocar ward" }).click()
  await choose(page, "Lado da ward", "Vermelho")
  const start = await mapPoint(page, 0.35, 0.25)
  await page.mouse.click(start.x, start.y)
  await page.getByRole("radio", { name: "Mover", exact: true }).click()
  const ward = page.getByRole("button", { name: "Mover Sentinela Invisível — Vermelho" })
  await expect(ward).toBeVisible()
  const lightBox = await boxOf(light)
  const wardBox = await boxOf(ward)
  await drag(
    page,
    { x: wardBox.x + wardBox.width / 2, y: wardBox.y + wardBox.height / 2 },
    { x: lightBox.x + lightBox.width / 2, y: lightBox.y + lightBox.height / 2 },
  )
  await expect(page.locator("#map-wards .ward-vision-bonus")).toHaveAttribute("data-faelight", "upper-island")
  await ward.press("ArrowRight")
  await expect(page.locator("#map-wards .ward-vision-bonus")).toHaveCount(0)
  await ward.press("ArrowLeft")
  await expect(page.locator("#map-wards .ward-vision-bonus")).toHaveCount(1)

  const placeWave = page.getByRole("radio", { name: "Colocar wave azul", exact: true })
  const placeRedWave = page.getByRole("radio", { name: "Colocar wave vermelha", exact: true })
  await placeWave.click()
  const location = await mapPoint(page, 0.45, 0.11)
  await page.mouse.click(location.x, location.y)
  await placeWave.click()
  const middle = await mapPoint(page, 0.57, 0.48)
  await page.mouse.click(middle.x, middle.y)
  await placeWave.click()
  const bottom = await mapPoint(page, 0.44, 0.92)
  await page.mouse.click(bottom.x, bottom.y)
  const waves = page.locator("#map-waves .map-wave")
  await expect(waves).toHaveCount(3)
  await expect(waves.locator("img.map-wave-caster")).toHaveCount(3)
  await placeRedWave.click()
  await expect(placeRedWave).toBeChecked()
  await page.mouse.click(bottom.x + 30, bottom.y)
  for (const [x, y] of [
    [0.45, 0.11],
    [0.57, 0.48],
  ]) {
    await placeRedWave.click()
    const point = await mapPoint(page, x, y)
    await page.mouse.click(point.x, point.y)
  }
  await expect(waves).toHaveCount(6)
  await expect(page.getByRole("button", { name: "Wave — Inferior — Vermelho" })).toBeVisible()
  await expect(page.getByRole("button", { name: "Wave — Inferior — Azul" })).toBeVisible()
  await expect(page.getByRole("radio", { name: "Mover", exact: true })).toBeChecked()
  const redTop = page.getByRole("button", { name: "Wave — Topo — Vermelho" })
  await redTop.click({ button: "right" })
  const waveMenu = page.getByRole("menu", { name: "Ações: Wave — Topo — Vermelho", exact: true })
  await expect(waveMenu).toBeVisible()
  await expect(page.locator("#map-context-target")).toBeVisible()
  await waveMenu.getByRole("menuitem", { name: "Excluir", exact: true }).click()
  await expect(waves).toHaveCount(5)
  await page.getByRole("button", { name: "Desfazer", exact: true }).click()
  await expect(waves).toHaveCount(6)
  const wave = page.getByRole("button", { name: "Wave — Topo — Azul" })
  const waveBox = await boxOf(wave)
  await drag(
    page,
    { x: waveBox.x + waveBox.width / 2, y: waveBox.y + waveBox.height / 2 },
    await mapPoint(page, 0.58, 0.48),
  )
  expect(Math.abs(Number.parseFloat(await wave.evaluate(button => button.style.top)) - 8.5)).toBeLessThan(2)
  const topWave = await wave.getAttribute("style")

  const layers = page.getByRole("group", { name: "Camadas do mapa" })
  await expect(layers.getByRole("switch")).toHaveCount(4)
  await layers.getByRole("switch", { name: "Alcance das torres" }).click()
  const tower = page.getByRole("button", { name: "Torre externa do topo — Azul" })
  await expect(page.locator("#map-tower-ranges circle")).toHaveCount(22)
  await page.getByRole("tab", { name: "Sequência" }).click()
  await page.getByRole("button", { name: "Novo passo" }).click()
  await tower.click({ button: "right" })
  await page.getByRole("menuitem", { name: "Marcar como destruída", exact: true }).click()
  await expect(tower).toHaveAttribute("aria-pressed", "true")
  await expect(page.locator("#map-tower-ranges circle")).toHaveCount(21)
  await wave.press("ArrowLeft")
  const movedWave = await wave.getAttribute("style")
  await page.getByRole("button", { name: "Novo passo" }).click()

  await visionButton(page, "vermelha").click()
  const waveSight = page.locator('#tactical-fog [data-sight-source="wave"][data-sight-radius="1200"]')
  await expect(waveSight).toHaveCount(3)
  await expect(page.locator("#tactical-fog [data-faelight-sight]")).toHaveCount(1)
  await expect(page.getByRole("button", { name: "Novo passo" })).toBeEnabled()
  await visionButton(page, "azul").click()
  await expect(waveSight).toHaveCount(3)
  await expect(page.locator("#tactical-fog [data-faelight-sight]")).toHaveCount(0)
  await visionButton(page, "azul e vermelha").click()
  await expect(waveSight).toHaveCount(6)
  await expect(page.locator('#tactical-fog [data-sight-source="ward"]')).toHaveCount(1)
  await expect(page.locator("#tactical-fog [data-faelight-sight]")).toHaveCount(1)
  await expect(page.locator('#tactical-fog [data-sight-source="tower"]')).toHaveCount(21)

  await page.getByRole("button", { name: "Selecionar passo 1" }).click()
  await expect(tower).toHaveAttribute("aria-pressed", "false")
  await expect(wave).toHaveAttribute("style", required(topWave, "estilo da onda no passo 1"))
  await page.getByRole("button", { name: "Reproduzir" }).click()
  await expect(tower).toHaveAttribute("aria-pressed", "true")
  await expect(wave).toHaveAttribute("style", required(movedWave, "estilo da onda movida"))
  await expect(page.getByRole("button", { name: "Reproduzir" })).toBeVisible()

  await visionButton(page, "geral").click()
  await page.getByRole("button", { name: "Limpar waves", exact: true }).click()
  await expect(waves).toHaveCount(0)
  await expect(ward).toHaveCount(1)
  await page.getByRole("button", { name: "Desfazer", exact: true }).click()
  await expect(waves).toHaveCount(6)
  await page.getByRole("button", { name: "Limpar tudo" }).click()
  await expect(waves).toHaveCount(0)
  await expect(ward).toHaveCount(0)
  await expect(tower).toHaveAttribute("aria-pressed", "true")
  await page.getByRole("button", { name: "Desfazer", exact: true }).click()
  await expect(waves).toHaveCount(6)
  await expect(ward).toHaveCount(1)
})
