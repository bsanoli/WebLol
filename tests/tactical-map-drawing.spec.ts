import { expect, test } from "@playwright/test"
import { size, visionButton, choose, mapPoint, drag } from "./support/tactical-map"

test("Setas retas e curvas encaixam o traço na ponta", async ({ page }) => {
  await page.setViewportSize(size)
  await page.goto("/camp.html")
  await page.getByRole("button", { name: "Mapa tático" }).click()
  const brush = page.getByRole("radio", { name: "Traço livre", exact: true })
  const arrowhead = page.getByRole("checkbox", { name: "Ponta de seta" })
  await brush.click()
  await arrowhead.check()
  await brush.click()
  await expect(arrowhead).toBeHidden()
  await expect(brush).toBeChecked()
  await brush.press("Space")
  await expect(arrowhead).toBeChecked()
  await brush.click()
  await expect(arrowhead).toBeHidden()
  const canvas = page.locator("#cv")
  await canvas.evaluate((node: HTMLCanvasElement) => {
    const context = node.getContext("2d")!
    let path: [number, number][] = []
    let strokeEnd: [number, number] | undefined
    const { beginPath, moveTo, lineTo, stroke, fill } = context
    context.beginPath = function () {
      path = []
      beginPath.call(this)
    }
    context.moveTo = function (x, y) {
      path.push([x, y])
      moveTo.call(this, x, y)
    }
    context.lineTo = function (x, y) {
      path.push([x, y])
      lineTo.call(this, x, y)
    }
    context.stroke = function () {
      strokeEnd = path.at(-1)
      stroke.call(this)
    }
    context.fill = function () {
      if (path.length === 3) {
        const [tip, a, b] = path
        const x = tip[0] - (a[0] + b[0]) / 2,
          y = tip[1] - (a[1] + b[1]) / 2
        const angle = Math.atan2(y, x)
        node.dataset.arrowAngle = String(angle)
        if (strokeEnd) {
          const inset = (tip[0] - strokeEnd[0]) * Math.cos(angle) + (tip[1] - strokeEnd[1]) * Math.sin(angle)
          node.dataset.shaftInset = String(inset / window.devicePixelRatio)
        }
      }
      fill.call(this)
    }
  })
  for (const zoom of [1, 1.25]) {
    if (zoom > 1) await page.getByRole("button", { name: "Aumentar zoom" }).click()
    for (const length of [14, 42]) {
      const end = await mapPoint(page, 0.55, 0.51)
      await page.mouse.move(end.x - length, end.y - length)
      await page.mouse.down()
      await page.mouse.move(end.x - length, end.y - 4, { steps: 5 })
      await page.mouse.move(end.x - length + 5, end.y)
      await page.mouse.move(end.x, end.y, { steps: 4 })
      const preview = Number(await canvas.getAttribute("data-arrow-angle"))
      expect(Number(await canvas.getAttribute("data-shaft-inset"))).toBeGreaterThan(4)
      await page.mouse.move(end.x, end.y + 1)
      await page.mouse.up()
      const saved = Number(await canvas.getAttribute("data-arrow-angle"))
      expect(Number(await canvas.getAttribute("data-shaft-inset"))).toBeGreaterThan(4)
      expect(Math.abs(saved - preview)).toBeLessThan(0.25)
      expect(Math.abs(saved)).toBeLessThan(0.45)
    }
  }
  await page.getByRole("radio", { name: "Desenhar seta", exact: true }).click()
  const start = await mapPoint(page, 0.37, 0.39)
  const end = await mapPoint(page, 0.57, 0.39)
  await page.mouse.move(start.x, start.y)
  await page.mouse.down()
  await page.mouse.move(end.x, end.y, { steps: 5 })
  expect(Number(await canvas.getAttribute("data-shaft-inset"))).toBeGreaterThan(4)
  await page.mouse.up()
  expect(Number(await canvas.getAttribute("data-shaft-inset"))).toBeGreaterThan(4)

  const clickStart = await mapPoint(page, 0.39, 0.44)
  const clickEnd = await mapPoint(page, 0.59, 0.37)
  await page.mouse.click(clickStart.x, clickStart.y)
  await page.mouse.click(clickEnd.x, clickEnd.y)
  expect(Number(await canvas.getAttribute("data-shaft-inset"))).toBeGreaterThan(4)
})

test("Aviso de visão e menus de ferramenta preservam a área e a câmera do mapa", async ({ page }) => {
  await page.setViewportSize(size)
  await page.emulateMedia({ reducedMotion: "reduce" })
  await page.goto("/#/time/mapa")
  await page.getByRole("button", { name: "Entrar sem usuário" }).click()
  const team = page.frameLocator("#v-camp")
  const viewport = team.getByRole("region", { name: "Mapa da jogada" })
  const board = team.locator("#map")
  const notice = team.getByText("Prévia tática aproximada da visão da equipe.")
  const options = team.getByRole("group", { name: "Opções de desenho" })
  const tool = (name: string) => team.getByRole("radio", { name, exact: true })
  const arrow = tool("Desenhar seta")
  const brush = tool("Traço livre")
  const bounds = async () => ({ viewport: await viewport.boundingBox(), board: await board.boundingBox() })

  await team.getByRole("button", { name: "Aumentar zoom" }).click()
  const initial = await bounds()
  for (const side of ["azul", "vermelha", "geral"] as const) {
    await visionButton(team, side).click()
    if (side === "geral") await expect(notice).toBeHidden()
    else await expect(notice).toBeVisible()
    expect(await bounds()).toEqual(initial)
  }

  await viewport.press("Shift+P")
  await expect(options).toBeVisible()
  await expect(brush).toBeChecked()
  await expect(options.getByRole("checkbox", { name: "Ponta de seta" })).toBeVisible()
  expect(await bounds()).toEqual(initial)
  const blue = options.getByRole("button", { name: "Azul", exact: true })
  await blue.click()
  await expect(blue).toHaveAttribute("aria-pressed", "true")
  const width = options.getByRole("combobox", { name: "Espessura" })
  await width.click()
  await team.getByRole("option", { name: "Grossa" }).click()
  await expect(width).toHaveText("Grossa")
  await expect(options).toBeVisible()
  await width.press("Escape")
  await expect(options).toBeHidden()
  await expect(brush).toBeFocused()
  expect(await bounds()).toEqual(initial)

  const ward = tool("Colocar ward")
  const wardOptions = team.getByRole("group", { name: "Opções de ward" })
  await ward.click()
  await expect(wardOptions).toBeVisible()
  expect(await bounds()).toEqual(initial)
  await choose(team, "Lado da ward", "Vermelho")
  const wardType = wardOptions.getByRole("combobox", { name: "Tipo de ward" })
  await wardType.click()
  await team.getByRole("option", { name: /^Sentinela de Controle/ }).click()
  await expect(wardOptions).toBeVisible()
  await wardType.press("Escape")
  await expect(wardOptions).toBeHidden()
  await expect(ward).toBeChecked()
  await expect(ward).toBeFocused()
  await ward.click()
  await expect(wardOptions).toBeVisible()
  const wardPoint = await mapPoint(team, 0.55, 0.52)
  await page.mouse.click(wardPoint.x, wardPoint.y)
  await expect(wardOptions).toBeHidden()
  await expect(team.getByRole("button", { name: "Mover Sentinela de Controle — Vermelho" })).toBeVisible()
  expect(await bounds()).toEqual(initial)

  await arrow.click()
  await expect(options).toBeVisible()
  await expect(options.getByRole("checkbox", { name: "Ponta de seta" })).toBeHidden()
  const start = await mapPoint(team, 0.39, 0.44)
  const end = await mapPoint(team, 0.59, 0.37)
  await page.mouse.click(start.x, start.y)
  await expect(options).toBeHidden()
  await expect(arrow).toBeChecked()
  await page.mouse.click(end.x, end.y)
  await expect(team.getByRole("button", { name: "Limpar setas", exact: true })).toBeEnabled()
  expect(await bounds()).toEqual(initial)

  await page.setViewportSize({ width: 800, height: 620 })
  await team.getByRole("button", { name: "Tela cheia", exact: true }).click()
  await expect(team.getByRole("button", { name: "Sair da tela cheia" })).toBeVisible()
  await visionButton(team, "azul").click()
  const narrow = await bounds()
  await arrow.click()
  await expect(options).toBeVisible()
  const panel = (await options.boundingBox())!,
    anchor = (await arrow.boundingBox())!
  expect(panel.y).toBeGreaterThanOrEqual(anchor.y + anchor.height)
  expect(panel.x).toBeGreaterThanOrEqual(0)
  expect(panel.x + panel.width).toBeLessThanOrEqual(800)
  await expect(notice).toBeVisible()
  expect(await bounds()).toEqual(narrow)
})

test("Desenha no zoom, limpa apenas setas e mantém a câmera em tela cheia", async ({ page }) => {
  await page.setViewportSize(size)
  await page.emulateMedia({ reducedMotion: "reduce" })
  await page.goto("/#/time/mapa")
  await page.getByRole("button", { name: "Entrar sem usuário" }).click()
  const team = page.frameLocator("#v-camp")
  const clearArrows = team.locator("#clr")
  const clearStrokes = team.locator("#map-clear-strokes")
  const clearAll = team.locator("#map-clear-all")
  await expect(clearArrows).toBeDisabled()
  const mover = team.getByRole("radio", { name: "Mover", exact: true })
  await expect(mover).toBeVisible()
  const toolsAtFit = (await mover.boundingBox())!
  expect(toolsAtFit.x).toBeCloseTo((await team.locator("#map").boundingBox())!.x)
  await expect(visionButton(team, "geral")).toHaveAttribute("aria-pressed", "true")
  await expect(team.getByRole("tab", { name: "Camadas" })).toBeVisible()

  const zoom = team.locator("#map-zoom-value")
  const viewport = team.getByRole("region", { name: "Mapa da jogada" })
  const camera = team.getByRole("group", { name: "Câmera do mapa" })
  const cameraAtFit = await camera.boundingBox()
  const area = (await viewport.boundingBox())!
  expect(area.x + area.width - (cameraAtFit!.x + cameraAtFit!.width)).toBeCloseTo(8)
  expect(area.y + area.height - (cameraAtFit!.y + cameraAtFit!.height)).toBeCloseTo(8)
  const anchor = await mapPoint(team, 0.5, 0.44)
  await page.mouse.move(anchor.x, anchor.y)
  await page.mouse.wheel(0, -120)
  await expect(zoom).toHaveText("127%")
  expect(await camera.boundingBox()).toEqual(cameraAtFit)
  const toolsAtZoom = (await mover.boundingBox())!
  expect(toolsAtZoom.x).toBeCloseTo(toolsAtFit.x, 1)
  expect(toolsAtZoom.y).toBeCloseTo(toolsAtFit.y, 1)
  const afterZoom = await mapPoint(team, 0.5, 0.44)
  expect(Math.abs(afterZoom.x - anchor.x)).toBeLessThan(1)
  expect(Math.abs(afterZoom.y - anchor.y)).toBeLessThan(1)
  await team.getByRole("button", { name: "Ajustar", exact: true }).click()
  const enlarge = team.getByRole("button", { name: "Aumentar zoom" })
  await enlarge.click()
  await enlarge.click()
  await expect(zoom).toHaveText("150%")
  await team.getByRole("radio", { name: "Mão", exact: true }).click()
  const transform = await team.locator("#map").evaluate(map => map.style.transform)
  await viewport.focus()
  await viewport.press("ArrowLeft")
  expect(await team.locator("#map").evaluate(map => map.style.transform)).not.toBe(transform)
  const brush = team.getByRole("radio", { name: "Traço livre", exact: true })
  await brush.click()
  const beforePan = await team.locator("#map").evaluate(map => map.style.transform)
  await page.mouse.move(anchor.x, anchor.y)
  await page.keyboard.down("Space")
  await expect(viewport).toHaveClass(/map-temporary-hand/)
  await drag(page, anchor, { x: anchor.x + 32, y: anchor.y + 20 })
  await page.keyboard.up("Space")
  await expect(viewport).not.toHaveClass(/map-temporary-hand/)
  expect(await team.locator("#map").evaluate(map => map.style.transform)).not.toBe(beforePan)
  const toolsAfterPan = (await mover.boundingBox())!
  expect(toolsAfterPan.x).toBeCloseTo(toolsAtFit.x, 1)
  expect(toolsAfterPan.y).toBeCloseTo(toolsAtFit.y, 1)
  await expect(clearAll).toBeDisabled()
  await brush.click()
  await choose(team, "Espessura", "Grossa")
  await choose(team, "Estilo", "Tracejado")
  await drag(page, await mapPoint(team, 0.47, 0.47), await mapPoint(team, 0.6, 0.56))
  await expect(clearAll).toBeEnabled()
  await expect(clearArrows).toBeDisabled()
  await brush.click()
  const arrowhead = team.getByRole("checkbox", { name: "Ponta de seta" })
  await expect(arrowhead).not.toBeChecked()
  await arrowhead.check()
  await drag(page, await mapPoint(team, 0.49, 0.48), await mapPoint(team, 0.62, 0.59))
  await expect(clearArrows).toBeEnabled()

  await team.getByRole("radio", { name: "Desenhar seta" }).click()
  await expect(arrowhead).toBeHidden()
  const start = await mapPoint(team, 0.41, 0.38)
  const end = await mapPoint(team, 0.6, 0.4)
  await page.mouse.click(start.x, start.y)
  await page.mouse.click(end.x, end.y)
  await clearArrows.click()
  await expect(clearArrows).toBeDisabled()
  await expect(clearAll).toBeEnabled()
  await clearStrokes.click()
  await expect(clearStrokes).toBeDisabled()
  await expect(clearAll).toBeDisabled()

  await team.getByRole("button", { name: "Tela cheia", exact: true }).click()
  await expect(team.getByRole("button", { name: "Sair da tela cheia" })).toBeVisible()
  await expect(zoom).toHaveText("150%")
  const center = await mapPoint(team, 0.5, 0.5)
  await page.mouse.move(center.x, center.y)
  await page.mouse.wheel(0, -120)
  await expect(zoom).toHaveText("191%")
  await page.keyboard.down("Space")
  await expect(viewport).toHaveClass(/map-temporary-hand/)
  await page.keyboard.up("Space")
  await visionButton(team, "azul").click()
  await expect(team.getByText("Prévia tática aproximada da visão da equipe.")).toBeVisible()
  await team.getByRole("button", { name: "Sair da tela cheia" }).click()
  await expect(zoom).toHaveText("191%")
  await visionButton(team, "geral").click()
  await team.getByRole("button", { name: "Ajustar", exact: true }).click()
  await expect(zoom).toHaveText("100%")
})
