test("Abre Camadas com ícones em 60% e mantém o tamanho escolhido", async ({ page }) => {
  await page.setViewportSize(size)
  await page.goto("/#/time/mapa")
  await page.getByRole("button", { name: "Entrar sem usuário" }).click()
  const team = page.frameLocator("#v-camp")
  const layers = team.getByRole("tab", { name: "Camadas" })
  const slider = team.getByRole("slider", { name: "Tamanho dos ícones" })
  const champion = team.getByRole("button", { name: "Azul TOP", exact: true })
  const scale = () => team.locator("#map").evaluate(board => board.style.getPropertyValue("--map-champion-scale"))

  await expect(layers).toHaveAttribute("aria-selected", "true")
  await expect(slider).toHaveAttribute("aria-valuetext", "60%")
  expect(await scale()).toBe("0.6")
  const initialWidth = (await champion.boundingBox())!.width

  await slider.press("ArrowRight")
  await expect(slider).toBeFocused()
  await expect(slider).toHaveAttribute("aria-valuetext", "61%")
  expect(await scale()).toBe("0.61")

  const track = (await team.locator("[data-slot=slider-track]").boundingBox())!
  const thumb = (await slider.boundingBox())!
  await page.mouse.move(thumb.x + thumb.width / 2, thumb.y + thumb.height / 2)
  await page.mouse.down()
  await page.mouse.move(track.x + track.width * .43, track.y + track.height / 2, { steps: 6 })
  await expect(slider).toHaveAttribute("aria-valuetext", "77%")
  expect(await scale()).toBe("0.77")
  await page.mouse.move(track.x + track.width - 1, track.y + track.height / 2, { steps: 6 })
  await page.mouse.up()
  await expect(slider).toHaveAttribute("aria-valuetext", "100%")
  expect((await champion.boundingBox())!.width).toBeGreaterThan(initialWidth)

  await slider.press("ArrowLeft")
  await expect(slider).toHaveAttribute("aria-valuetext", "99%")
  await team.getByRole("tab", { name: "Sequência" }).click()
  await layers.click()
  await expect(slider).toHaveAttribute("aria-valuetext", "99%")
  await page.reload()
  const enter = page.getByRole("button", { name: "Entrar sem usuário" })
  if (await enter.isVisible()) await enter.click()
  await expect(layers).toHaveAttribute("aria-selected", "true")
  await expect(slider).toHaveAttribute("aria-valuetext", "99%")
  expect(await scale()).toBe("0.99")
})

