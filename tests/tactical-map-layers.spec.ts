import { expect, test } from "@playwright/test"
import { size, vision, visionButton, mapPoint, drag, waitForRealisticMap } from "./support/tactical-map"

test("Abre Camadas com ícones em 60% e mantém o tamanho escolhido", async ({ page }) => {
  await page.setViewportSize(size)
  await page.goto("/#/time/mapa")
  await page.getByRole("button", { name: "Entrar sem usuário" }).click()
  const team = page.frameLocator("#v-camp")
  await waitForRealisticMap(team)
  const layers = team.getByRole("tab", { name: "Camadas" })
  const slider = team.getByRole("slider", { name: "Tamanho dos ícones" })
  const champion = team.getByRole("button", { name: "Azul TOP", exact: true })
  const scale = () => team.locator("#map").evaluate(board => board.style.getPropertyValue("--map-champion-scale"))

  await expect(layers).toHaveAttribute("aria-selected", "true")
  await expect(slider).toHaveAttribute("aria-valuetext", "60%")
  expect(await scale()).toBe("0.6")
  const initialWidth = (await champion.boundingBox())!.width

  await slider.press("ArrowRight")
  await expect(slider).toBeFocused()
  await expect(slider).toHaveAttribute("aria-valuetext", "61%")
  expect(await scale()).toBe("0.61")

  const track = (await team.locator("[data-slot=slider-track]").boundingBox())!
  const thumb = (await slider.boundingBox())!
  await page.mouse.move(thumb.x + thumb.width / 2, thumb.y + thumb.height / 2)
  await page.mouse.down()
  await page.mouse.move(track.x + track.width * 0.43, track.y + track.height / 2, { steps: 6 })
  await expect(slider).toHaveAttribute("aria-valuetext", "77%")
  expect(await scale()).toBe("0.77")
  await page.mouse.move(track.x + track.width - 1, track.y + track.height / 2, { steps: 6 })
  await page.mouse.up()
  await expect(slider).toHaveAttribute("aria-valuetext", "100%")
  expect((await champion.boundingBox())!.width).toBeGreaterThan(initialWidth)

  await slider.press("ArrowLeft")
  await expect(slider).toHaveAttribute("aria-valuetext", "99%")
  await team.getByRole("tab", { name: "Sequência" }).click()
  await layers.click()
  await expect(slider).toHaveAttribute("aria-valuetext", "99%")
  await page.reload()
  const enter = page.getByRole("button", { name: "Entrar sem usuário" })
  // Depois do reload o login ou a Área do time ainda estão sendo montados: espera um dos dois antes de decidir.
  await expect.poll(async () => (await enter.isVisible()) || (await layers.isVisible())).toBe(true)
  if (await enter.isVisible()) await enter.click()
  await expect(layers).toHaveAttribute("aria-selected", "true")
  await expect(slider).toHaveAttribute("aria-valuetext", "99%")
  expect(await scale()).toBe("0.99")
})

test("Edita o lado da ward junto à peça sem alterar a câmera", async ({ page }) => {
  await page.setViewportSize({ width: 1180, height: 850 })
  await page.goto("/#/time/mapa")
  await page.getByRole("button", { name: "Entrar sem usuário" }).click()
  const team = page.frameLocator("#v-camp")
  await waitForRealisticMap(team)
  const board = team.locator("#map")
  const viewport = team.getByRole("region", { name: "Mapa da jogada" })
  const editor = team.getByRole("dialog", { name: "Lado da ward" })
  const blue = team.getByRole("button", { name: "Mover Sentinela Invisível — Azul" })
  const red = team.getByRole("button", { name: "Mover Sentinela Invisível — Vermelho" })
  await team.getByRole("radio", { name: "Colocar ward" }).click()
  const edge = await mapPoint(team, 0.98, 0.91)
  await page.mouse.click(edge.x, edge.y)
  await team.getByRole("radio", { name: "Mover", exact: true }).click()

  const assertFits = async () => {
    const area = (await viewport.boundingBox())!
    const menu = (await editor.boundingBox())!
    const camera = (await team.getByRole("group", { name: "Câmera do mapa" }).boundingBox())!
    expect(menu.x).toBeGreaterThanOrEqual(area.x)
    expect(menu.y).toBeGreaterThanOrEqual(area.y)
    expect(menu.x + menu.width).toBeLessThanOrEqual(area.x + area.width)
    expect(menu.y + menu.height).toBeLessThanOrEqual(area.y + area.height)
    expect(menu.y + menu.height).toBeLessThanOrEqual(camera.y)
  }

  const initial = await board.boundingBox()
  await blue.click()
  await expect(editor.getByRole("button", { name: "Azul" })).toHaveAttribute("aria-pressed", "true")
  await expect(blue).toHaveAttribute("aria-expanded", "true")
  expect(await board.boundingBox()).toEqual(initial)
  await assertFits()
  await editor.getByRole("button", { name: "Vermelho" }).press("Enter")
  await expect(red).toBeFocused()
  await expect(team.locator(".ward-vision-range")).toHaveAttribute("data-side", "r")
  await team.getByRole("button", { name: "Desfazer", exact: true }).click()
  await expect(blue).toBeVisible()

  await blue.press("Space")
  await expect(editor.getByRole("button", { name: "Azul" })).toBeFocused()
  await page.keyboard.press("Escape")
  await expect(blue).toBeFocused()
  await expect(editor).toBeHidden()
  await blue.press("Enter")
  const outside = await mapPoint(team, 0.5, 0.5)
  await page.mouse.click(outside.x, outside.y)
  await expect(editor).toBeHidden()
  await blue.press("Enter")
  await team.getByRole("button", { name: "Aumentar zoom" }).click()
  await expect(editor).toBeHidden()
  await team.getByRole("button", { name: "Ajustar" }).click()

  await team.getByRole("button", { name: "Tela cheia", exact: true }).click()
  const exitFullscreen = team.getByRole("button", { name: "Sair da tela cheia" })
  await expect(exitFullscreen).toBeVisible()
  const expanded = await board.boundingBox()
  await blue.click()
  await assertFits()
  expect(await board.boundingBox()).toEqual(expanded)
  await page.keyboard.press("Escape")
  await expect(editor).toBeHidden()
  await expect(exitFullscreen).toBeVisible()

  const ward = (await blue.boundingBox())!
  await drag(page, { x: ward.x + ward.width / 2, y: ward.y + ward.height / 2 }, await mapPoint(team, 0.82, 0.75))
  await expect(editor).toBeHidden()
  await expect(team.locator(".ward-vision-range")).toHaveAttribute("cx", "82")
})

test("Atalhos alternam ferramentas e a Borracha apaga uma ward antes do traço sobreposto", async ({ page }) => {
  await page.setViewportSize(size)
  await page.goto("/camp.html")
  await page.getByRole("button", { name: "Mapa tático" }).click()
  await waitForRealisticMap(page)
  const viewport = page.getByRole("region", { name: "Mapa da jogada" })
  const tool = (name: string) => page.getByRole("radio", { name, exact: true })
  await viewport.press("h")
  await expect(tool("Mão")).toBeChecked()
  await tool("Mão").press("v")
  await expect(tool("Mover")).toBeFocused()
  await viewport.press("Shift+p")
  await expect(tool("Traço livre")).toBeChecked()
  await viewport.press("Shift+l")
  await expect(tool("Desenhar seta")).toBeChecked()
  await drag(page, await mapPoint(page, 0.33, 0.35), await mapPoint(page, 0.53, 0.35))
  await tool("Colocar ward").click()
  let intersection = await mapPoint(page, 0.43, 0.35)
  await page.mouse.click(intersection.x, intersection.y)

  await tool("Colocar ward").click()
  await page.getByText("Ajuda", { exact: true }).click()
  await viewport.press("b")
  await expect(tool("Colocar ward")).toBeChecked()
  await page.getByText("Ajuda", { exact: true }).click()
  await viewport.press("b")
  await expect(tool("Borracha")).toBeChecked()
  const ward = page.getByRole("button", { name: "Apagar Sentinela Invisível — Azul" })
  const clearArrows = page.locator("#clr")
  intersection = await mapPoint(page, 0.43, 0.35)
  await page.mouse.click(intersection.x, intersection.y)
  await expect(ward).toHaveCount(0)
  await expect(clearArrows).toBeEnabled()
  await page.getByRole("button", { name: "Desfazer", exact: true }).click()
  await ward.press("Shift+F10")
  const wardMenu = page.getByRole("menu", { name: "Ações: Sentinela Invisível — Azul" })
  const selection = page.locator("#map-context-target")
  await expect(wardMenu).toBeVisible()
  await expect(selection).toBeVisible()
  await wardMenu.getByRole("menuitem", { name: "Excluir", exact: true }).press("Escape")
  await expect(selection).toBeHidden()
  await expect(ward).toBeFocused()
  await ward.press("Shift+F10")
  await wardMenu.getByRole("menuitem", { name: "Excluir", exact: true }).press("Enter")
  await expect(selection).toBeHidden()
  await expect(ward).toHaveCount(0)
  await expect(viewport).toBeFocused()
  await expect(clearArrows).toBeEnabled()
  const canvas = page.locator("#cv")
  const picture = () => canvas.evaluate((node: HTMLCanvasElement) => node.toDataURL())
  await page.mouse.move(intersection.x - 60, intersection.y - 60)
  const normal = await picture()
  await page.mouse.click(intersection.x, intersection.y, { button: "right" })
  const lineMenu = page.getByRole("menu", { name: "Ações: Seta", exact: true })
  await expect(lineMenu).toBeVisible()
  expect(await picture()).not.toBe(normal)
  await page.mouse.click(intersection.x - 60, intersection.y - 60)
  await expect(lineMenu).toBeHidden()
  expect(await picture()).toBe(normal)
  await page.mouse.click(intersection.x, intersection.y, { button: "right" })
  await lineMenu.getByRole("menuitem", { name: "Excluir", exact: true }).click()
  await expect(clearArrows).toBeDisabled()
  await viewport.press("v")
  await viewport.press("e")
  await expect(tool("Borracha")).toBeChecked()
  await page.getByRole("tab", { name: "Jogada", exact: true }).click()
  await page.getByRole("button", { name: "Nova jogada", exact: true }).click()
  const name = page.getByRole("dialog").getByRole("textbox")
  await name.fill("")
  await name.pressSequentially("bhv")
  await expect(name).toHaveValue("bhv")
  await name.press("Escape")
  await expect(tool("Borracha")).toBeChecked()
  await visionButton(page, "azul").click()
  await expect(tool("Borracha")).toBeChecked()
  await viewport.press("Shift+l")
  await expect(tool("Desenhar seta")).toBeChecked()
  await drag(page, await mapPoint(page, 0.33, 0.35), await mapPoint(page, 0.53, 0.35))
  await expect(clearArrows).toBeEnabled()
  await visionButton(page, "vermelha").click()
  await expect(tool("Desenhar seta")).toBeChecked()
  await viewport.press("b")
  await expect(tool("Borracha")).toBeChecked()
  const redIntersection = await mapPoint(page, 0.43, 0.35)
  await page.mouse.click(redIntersection.x, redIntersection.y)
  await expect(clearArrows).toBeDisabled()
})

test("Reabre opções da barra, guarda cor e tamanho do cursor e oferece ferramentas no mapa vazio", async ({ page }) => {
  await page.setViewportSize(size)
  await page.goto("/camp.html")
  await page.getByRole("button", { name: "Mapa tático" }).click()
  await waitForRealisticMap(page)
  const tool = (name: string) => page.getByRole("radio", { name, exact: true })
  for (const [name, panelId] of [
    ["Desenhar seta", "map-arrow-options"],
    ["Traço livre", "map-arrow-options"],
    ["Colocar ward", "map-ward-options"],
  ]) {
    const panel = page.locator(`#${panelId}`)
    await tool(name).click()
    await expect(panel).toBeVisible()
    await tool(name).click()
    await expect(panel).toBeHidden()
    await expect(tool(name)).toBeChecked()
    await tool(name).click()
    await expect(panel).toBeVisible()
  }

  const cursorMenu = page.locator("#map-cursor-menu summary")
  const cursorOptions = page.getByRole("group", { name: "Cores do cursor" })
  const cursorSize = page.getByRole("group", { name: "Tamanho do cursor" })
  await cursorMenu.click()
  await cursorOptions.getByRole("button", { name: "Azul" }).click()
  await cursorSize.getByRole("button", { name: "Grande" }).click()
  await cursorMenu.click()
  await expect(cursorOptions).toBeHidden()

  const viewport = page.getByRole("region", { name: "Mapa da jogada" })
  const quickMenu = page.getByRole("menu", { name: "Ferramentas do mapa", exact: true })
  const empty = await mapPoint(page, 0.54, 0.46)
  await page.mouse.click(empty.x, empty.y, { button: "right" })
  await expect(quickMenu.getByRole("menuitem", { name: "Desfazer", exact: true })).toBeDisabled()
  await expect(quickMenu.getByRole("menuitemradio")).toHaveCount(5)
  await quickMenu.getByRole("menuitemradio", { name: "Mão", exact: true }).click()
  await expect(tool("Mão")).toBeChecked()
  await expect(page.locator("#map")).toHaveCSS("cursor", /width%3D%2240%22.*78beff.*\) 20 22, grab/)

  await viewport.press("Shift+F10")
  const hand = quickMenu.getByRole("menuitemradio", { name: "Mão", exact: true })
  await expect(hand).toBeFocused()
  await hand.press("ArrowDown")
  const arrow = quickMenu.getByRole("menuitemradio", { name: "Desenhar seta", exact: true })
  await expect(arrow).toBeFocused()
  await arrow.press("Enter")
  await expect(tool("Desenhar seta")).toBeChecked()
  await drag(page, await mapPoint(page, 0.37, 0.41), await mapPoint(page, 0.57, 0.41))
  const clearArrows = page.getByRole("button", { name: "Limpar setas", exact: true })
  await expect(clearArrows).toBeEnabled()
  await viewport.press("Shift+F10")
  await quickMenu.getByRole("menuitem", { name: "Desfazer", exact: true }).click()
  await expect(clearArrows).toBeDisabled()
  await viewport.press("Shift+F10")
  await quickMenu.getByRole("menuitem", { name: "Refazer", exact: true }).click()
  await expect(clearArrows).toBeEnabled()

  await page.reload()
  await page.getByRole("button", { name: "Mapa tático" }).click()
  await waitForRealisticMap(page)
  await cursorMenu.click()
  await expect(cursorOptions.getByRole("button", { name: "Azul" })).toHaveAttribute("aria-pressed", "true")
  await expect(cursorSize.getByRole("button", { name: "Grande" })).toHaveAttribute("aria-pressed", "true")
  await expect(page.locator("#map")).toHaveCSS("cursor", /width%3D%2240%22.*78beff.*\) 7 5, default/)
})
